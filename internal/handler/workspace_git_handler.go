// gitConflictsAbort handles POST /api/workspaces/{id}/git/conflicts/abort.
func (h *Handler) gitConflictsAbort(w http.ResponseWriter, r *http.Request) {
	id, ok := parseUUID(w, r, "id")
	if !ok {
		return
	}

	var req struct {
		RepoID string `json:"repo_id"`
	}
	if !decodeJSON(w, r, &req) {
		return
	}

	repos, _ := h.wsRepoRepo.FindByWorkspaceIDWithRepos(id)
	target := findRepoByID(repos, req.RepoID)
	if target == nil {
		badRequest(w, "repo not found in workspace")
		return
	}

	if err := h.gitSvc.AbortConflicts(target.Path); err != nil {
		internalError(w, "failed to abort conflicts: "+err.Error())
		return
	}
	success(w, map[string]string{"status": "aborted"})
}

