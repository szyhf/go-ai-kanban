// gitForcePush handles POST /api/workspaces/{id}/git/push/force.
func (h *Handler) gitForcePush(w http.ResponseWriter, r *http.Request) {
	id, ok := parseUUID(w, r, "id")
	if !ok {
		return
	}

	ws, err := h.wsRepo.FindByID(id)
	if err != nil || ws == nil {
		notFound(w, "workspace not found")
		return
	}

	var req struct {
		RepoID string `json:"repo_id"`
	}
	if !decodeJSON(w, r, &req) {
		return
	}

	repos, _ := h.wsRepoRepo.FindByWorkspaceIDWithRepos(id)
	var results []map[string]string
	for _, rwt := range repos {
		if req.RepoID != "" && rwt.ID.String() != req.RepoID {
			continue
		}
		err := h.gitSvc.PushToRemote(rwt.Path, ws.Branch, true)
		status := "pushed"
		errMsg := ""
		if err != nil {
			status = "error"
			errMsg = err.Error()
		}
		results = append(results, map[string]string{
			"repo_id": rwt.ID.String(),
			"status":  status,
			"error":   errMsg,
		})
	}
	success(w, results)
}

